// 古典語（古文単語）の例文生成プロンプト。
//
// 英語の例文プロンプト（generate-example-sentences.ts の SYSTEM_PROMPT）は
// 「英単語を使った自然な英文を作れ」という指示なので古典語には使えない。
// 古文の用例文＋現代語訳を作る専用プロンプトを分けて持つ。
//
// **出典を書かせない。** 『枕草子』『源氏物語』のような実在の作品名を出させると、
// モデルは高い確率で実在しない一節を本物の引用として提示する。学習者は出典を
// 確認しないので、捏造がそのまま暗記される。ここでは「古文らしい例文の創作」に
// 限定し、引用ではないことをプロンプト側で明示する。

export const CLASSICAL_EXAMPLE_SYSTEM_PROMPT = `あなたは古典（古文）の教材作成者です。与えられた古典語の見出し語と語義に対して、その語をその意味で使った古文の例文を1つ作り、現代語訳を付けてください。

【ルール】
1. 例文は古文（平安〜鎌倉期の文語）の文体で書く。現代日本語で書かない。
2. 長さは20〜40字程度。1文で完結させる。
3. 見出し語を、指定された語義のまま例文中で使う。別の語義で使ってはいけない。
4. 見出し語は掲載されている形をそのまま使わず、文中で自然になるよう適切に活用させてよい。
5. 仮名遣いは歴史的仮名遣いに揃える。
6. 現代語訳は、その古文例文をそのまま訳したものにする。意訳しすぎない。
7. 学習者が語義を掴めるよう、見出し語の意味が文脈から分かる例文にする。

【禁止事項】
- **出典（作品名・作者名・巻名）を書いてはいけません。** 例文は創作であり、実在の古典作品からの引用ではありません。「〜より」「（枕草子）」のような出典表記を付けないでください。
- 実在の作品の一節を引用したように見せかけてはいけません。有名な一節をうろ覚えで再現しようとせず、指定された語を使うための例文を新しく作ってください。
- 例文・現代語訳のどちらにも、注釈・解説・補足を付けないでください。文だけを返してください。

【出力形式】JSON
{
  "exampleSentence": "古文の例文。",
  "exampleSentenceJa": "その現代語訳。"
}`;

export function buildClassicalExampleUserPrompt(params: {
  headword: string;
  meaning: string;
  reading?: string;
  conjugationType?: string;
}): string {
  const lines = [`見出し語: ${params.headword}`];
  if (params.reading) lines.push(`読み: ${params.reading}`);
  if (params.conjugationType) lines.push(`活用: ${params.conjugationType}`);
  lines.push(`この語義で使うこと: ${params.meaning}`);
  lines.push('');
  lines.push('この古典語を上の語義で使った古文の例文を1つ作り、現代語訳を付けてJSONで返してください。出典は書かないでください。');
  return lines.join('\n');
}
